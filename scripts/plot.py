# All-heads grids for Task G — every self-attention head of the trained model,
# read from the "transformer" run tag and keyed by mask state so a leaky and a
# correct run draw as separate grids (leaky-vs-correct, observe before fix).
# ---------------------------------------------------------------------------


def _runs_by_state(pinned: str | None, tag: str) -> dict[bool, Any]:
    """Runs of *tag* keyed by causal-mask state, newest of each state winning.

    Run the demo before fixing the mask and again after, so both a leaky and a
    correct run are on disk; each becomes its own all-heads grid.
    """
    from attention.run import all_runs

    dirs = [_resolve(pinned, tag)] if pinned else all_runs(_RESULTS, tag)
    by_state: dict[bool, Any] = {}
    for run_dir in dirs:
        data = _load(run_dir, "train_transformer.json")
        if data is not None and "mask_ok" in data:
            by_state[bool(data["mask_ok"])] = data
    return by_state


def _head_grid(data: Any, state_label: str, out: str) -> None:
    """Draw every (layer, head) self-attention map of one run as a grid.

    No head is selected — that is the point.  The reader scans all of them and
    sees for themselves that most heads are diffuse and only a few read the next
    token; selecting the max-future-mass head would be circular (sorting on the
    quantity the figure claims to reveal).  Each panel is titled with its own
    future-attention-mass, and the square marks ``key = query + 1``.
    """
    entries = data["head_maps"]
    tokens = data["tokens"]
    panels = [(f"L{h['layer']} H{h['head']} · future {h['future_mass']:.0%}", np.array(h["map"])) for h in entries]
    overlays = [diagonal_overlay(len(tokens), 1) for _ in entries]
    heatmap_grid(
        panels,
        title=f"Every head of the {state_label} decoder-only transformer (Copy n=8)\n"
        "most heads are diffuse; the leak, when present, lives in a few — no head is cherry-picked",
        xlabel="key position (attended to)",
        ylabel="query position",
        out=out,
        cmap="magma",
        ncols=data.get("num_heads", 4),
        overlays=overlays,
        overlay_label="key = query + 1 (the next token)",
        xticklabels=tokens,
        yticklabels=tokens,
        gamma=2.0,
    )


_TASK_FIGS: dict[str, Callable[[str | None], _Builders]] = {
    "b": _figs_b,
    "c": _figs_c,
    "d": _figs_d,
    "e": _figs_e,
    "f": _figs_f,
    "g": _figs_g,
    "h": _figs_h,
    "i": _figs_i,
}


def plot_task(task: str, fig: str | None, run: str | None) -> None:
    if task == "a":
        print("Task A has no figure (no training or data to plot). The first real figure is Task B's training curve.")
        return
    if task == "battery":
        if _cumulative_scoreboard()():
            print(f"wrote {_FIGURES / 'battery.png'}")
        else:
            print("no battery scoreboards on disk yet — run a battery task's demo first.")
        return
    if task not in _TASK_FIGS:
        raise SystemExit(f"unknown task {task!r} (expected a-i)")
    builders = _TASK_FIGS[task](run)
    names = [name for name, _ in builders]
    if fig is not None and fig not in names:
        raise SystemExit(f"unknown figure {fig!r} for task {task!r} (expected one of {names})")
    for name, build in builders:
        if fig is not None and fig != name:
            continue
        if build():
            print(f"wrote {_out(task, name)}")
        else:
            print(f"no data for figure {name!r} — run `make demo-{task}` first.")


def main() -> None:
    parser = argparse.ArgumentParser(description="A6 figure dispatcher")
    parser.add_argument("task", help="task letter (a-i)")
    parser.add_argument("--fig", default=None, help="render one named figure")
    parser.add_argument("--run", default=None, help="pin a specific run dir")
    args = parser.parse_args()
    _FIGURES.mkdir(parents=True, exist_ok=True)
    plot_task(args.task, args.fig, args.run)


if __name__ == "__main__":
    main()
