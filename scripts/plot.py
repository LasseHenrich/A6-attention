def _figs_b(pinned: str | None) -> _Builders:
    run = _resolve(pinned, "rnn")

    def training_curve() -> bool:
        metrics = _load(run, "metrics.json")
        if metrics is None:
            return False
        series = {task: (h["steps"], h["train_loss"]) for task, h in metrics.items()}
        line_plot(
            series,
            title="RNN training loss across the battery",
            xlabel="step",
            ylabel="masked cross-entropy",
            out=_out("b", "training-curve"),
        )
        return True

    return [("training-curve", training_curve)]


def _figs_c(pinned: str | None) -> _Builders:
    run = _resolve(pinned, "bahdanau")

    def recall() -> bool:
        data = _load(run, "recall_vs_distance.json")
        if data is None:
            return False
        xs = data["needle_distance"]
        series = {label: (xs, data[label]) for label in ("rnn", "rnn_bahdanau") if label in data}
        line_plot(
            series,
            title="Associative recall vs needle distance",
            xlabel="needle distance (pairs before the query)",
            ylabel="token accuracy",
            out=_out("c", "recall-vs-distance"),
        )
        return True

    def grad_norm() -> bool:
        data = _load(run, "gradient_probe.json")
        if data is None:
            return False
        line_plot(
            {"decoder loss → source embedding": (data["source_position"], data["grad_norm"])},
            title="Gradient norm reaching each source position",
            xlabel="source position",
            ylabel="grad norm (log)",
            out=_out("c", "grad-norm"),
            logy=True,
        )
        return True

    def serial_timing() -> bool:
        data = _load(run, "serial_timing.json")
        if data is None:
            return False
        times = data["forward_seconds"]
        line_plot(
            {"RNN+attention forward": (data["length"], relative_to_baseline(times, times[0]))},
            title="Inference wall-clock vs sequence length",
            xlabel="sequence length",
            ylabel="time (× shortest length; machine-relative)",
            out=_out("c", "serial-timing"),
        )
        return True

    return [
        ("recall-vs-distance", recall),
        ("grad-norm", grad_norm),
        ("serial-timing", serial_timing),
    ]


def _figs_d(pinned: str | None) -> _Builders:
    scaling_run = _resolve(pinned, "scaling")
    equiv_run = _resolve(pinned, "equivariance")

    def _scaling_metric(metric: str, ylabel: str, *, logy: bool) -> bool:
        data = _load(scaling_run, "scaling_ablation.json")
        if data is None:
            return False
        xs = data["d_k"]
        series = {arm: (xs, data[f"{metric}_{arm}"]) for arm in ("scaled", "unscaled")}
        line_plot(
            series,
            title=f"Scaling ablation — {ylabel} vs d_k",
            xlabel="key dimension d_k",
            ylabel=ylabel,
            out=_out("d", metric.replace("_", "-")),
            logx=True,
            logy=logy,
        )
        return True

    def equivariance() -> bool:
        data = _load(equiv_run, "permutation_equivariance.json")
        if data is None or "position_free_accuracy" not in data:
            return False
        groups = {task: {"position-free single layer": acc} for task, acc in data["position_free_accuracy"].items()}
        grouped_bars(
            groups,
            title=f"Order tasks without positions (equivariance gap {data['equivariance_gap']:.1e})",
            ylabel="token accuracy",
            out=_out("d", "permutation-equivariance"),
        )
        return True

    return [
        ("logit-var", lambda: _scaling_metric("logit_var", "pre-softmax logit variance", logy=True)),
        ("softmax-max", lambda: _scaling_metric("softmax_max", "softmax max probability", logy=False)),
        ("grad-norm", lambda: _scaling_metric("grad_norm", "query grad norm", logy=True)),
        ("permutation-equivariance", equivariance),
    ]


def _figs_e(pinned: str | None) -> _Builders:
    run = _resolve(pinned, "two-relation")

    def accuracy() -> bool:
        data = _load(run, "two_relation.json")
        if data is None:
            return False
        groups = {label: {"two-relation accuracy": acc} for label, acc in data["accuracy"].items()}
        grouped_bars(
            groups,
            title="Two-relation task: single vs multi-head",
            ylabel="token accuracy",
            out=_out("e", "two-relation"),
        )
        return True

    def entropy() -> bool:
        data = _load(run, "two_relation.json")
        if data is None or not data.get("per_head_entropy"):
            return False
        groups = {label: {f"head {i}": e for i, e in enumerate(entropies)} for label, entropies in data["per_head_entropy"].items()}
        grouped_bars(
            groups,
            title="Per-head attention entropy (trained)",
            ylabel="entropy (nats)",
            out=_out("e", "head-entropy"),
        )
        return True

    def decomposition() -> bool:
        """The average hides it: two relations are free, one carries the story."""
        data = _load(run, "two_relation.json")
        if data is None or "sweep" not in data:
            return False
        sweep = data["sweep"]
        xs = sweep["num_heads"]
        # EOS is 1.000 everywhere and would be drawn exactly on top of relation
        # A, hiding it.  It is named in the title instead of plotted.
        keys = [k for k in sorted(sweep["per_seed"][f"heads_{xs[0]}"]) if k != "EOS"]
        series: dict[str, Any] = {}
        bands: dict[str, Any] = {}
        for key in keys:
            runs = [sweep["per_seed"][f"heads_{h}"][key] for h in xs]
            series[key] = (xs, [sum(r) / len(r) for r in runs])
            bands[key] = ([min(r) for r in runs], [max(r) for r in runs])
        line_plot(
            series,
            title=f"Two-relation task, per output position ({sweep['seeds']} seeds; band = min–max)\nthe third position, EOS, is 1.000 everywhere",
            xlabel="number of heads",
            ylabel="token accuracy",
            out=_out("e", "relation-decomposition"),
            bands=bands,
            hlines=[(data["chance"], "chance"), (data["value_set_prior"], "value-set prior")],
            logx=True,
            xticks=xs,
        )
        return True

    def head_attention() -> bool:
        """What each head attends to at the two output queries."""
        data = _load(run, "two_relation.json")
        if data is None or not data.get("head_attention"):
            return False
        h = data["head_attention"]
        rows = np.array(h["rows"])  # [H, 2, L]
        correct = h["correct_columns"]
        overlay = [(0, correct[0]), (1, correct[1])]
        heatmap_grid(
            [(f"head {i}", rows[i]) for i in range(rows.shape[0])],
            title="Where each head looks at the two output queries",
            xlabel="key position (role: sampled token)",
            cbar_label="attention weight",
            out=_out("e", "head-attention"),
            xticklabels=h.get("key_labels", h["tokens"]),
            yticklabels=h["query_labels"],
            overlays=[overlay] * rows.shape[0],
            overlay_label="correct source",
            ncols=2,
            xtick_rotation=45,
            ytick_rotation=45,
        )
        return True

    return [
        ("two-relation", accuracy),
        ("head-entropy", entropy),
        ("relation-decomposition", decomposition),
        ("head-attention", head_attention),
    ]


