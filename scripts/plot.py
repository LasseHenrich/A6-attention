def _figs_g(pinned: str | None) -> _Builders:
    def _heads(mask_ok: bool, name: str, state_label: str) -> Callable[[], bool]:
        """Every head of the leaky / correct model, no head cherry-picked.

        Replaces the old last-layer head-mean map: averaging over heads smears
        a sharp single-head leak into a faint haze.  The grid shows all heads so
        the reader finds the peeking ones themselves, and needs both a buggy and
        a fixed run on disk to draw both states.
        """

        def build() -> bool:
            by_state = _runs_by_state(pinned, "transformer")
            if mask_ok not in by_state or "head_maps" not in by_state[mask_ok]:
                return False
            _head_grid(by_state[mask_ok], state_label, _out("g", name))
            return True

        return build

    def by_position() -> bool:
        """The leak's cost per token — buggy vs fixed, side by side.

        One panel per mask state, on a shared y-axis: under the bug the
        free-running curve falls away from teacher-forced; once fixed the two
        rejoin near the top.  Needs a buggy and a fixed run on disk for both
        panels (a single run draws its one panel).
        """
        by_state = _runs_by_state(pinned, "transformer")
        panels, n = [], None
        for mask_ok, panel_title in [(False, "mask still buggy (leaky)"), (True, "mask fixed (correct)")]:
            data = by_state.get(mask_ok)
            if data is None or "by_position" not in data:
                continue
            p = data["by_position"]
            n = data["by_position_length"]
            panels.append((panel_title, {label: (p["position"], p[label]) for label in ("teacher_forced", "free_running")}))
        if not panels:
            return False
        line_grid(
            panels,
            title=f"Accuracy at each generated token (copy, n={n})",
            xlabel="output token index",
            ylabel="token accuracy",
            out=_out("g", "accuracy-by-position"),
            hline=1.0 / N_CONTENT,
            hline_label="chance",
            ncols=2,
            marker="o",
            xinteger=True,
            label_refs_each=True,
        )
        return True

    return [
        ("heads-leaky", _heads(False, "heads-leaky", "leaky")),
        ("heads-correct", _heads(True, "heads-correct", "correct")),
        ("accuracy-by-position", by_position),
    ]


def _figs_h(pinned: str | None) -> _Builders:
    run = _resolve(pinned, "sort-gap")

    def alignment() -> bool:
        """Both architectures learn the same argsort: self-attention vs cross-attention."""
        data = _load(run, "sort_gap.json")
        if data is None or "decoder_only_alignment" not in data:
            return False
        dec_peak, enc_peak = data["decoder_only_peakiness"], data["encoder_decoder_peakiness"]
        panels = {
            f"decoder-only: self-attention\n(output → source, peakiness {dec_peak:.2f})": np.array(data["decoder_only_alignment"]),
            f"encoder-decoder: cross-attention\n(decoder → memory, peakiness {enc_peak:.2f})": np.array(data["encoder_decoder_alignment"]),
        }
        # Both models see the same example, so one argsort overlays both panels.
        overlay = list(enumerate(data["encoder_decoder_argsort"]))
        attention_heatmap(
            panels,
            title=f"Both architectures learn the same argsort alignment (Sort, n={data['n']})",
            xlabel="source position",
            ylabel="output step",
            out=_out("h", "alignment"),
            xticklabels=data["encoder_decoder_source"],
            yticklabels=[f"y{i + 1}" for i in range(data["n"])],
            overlay=overlay,
            overlay_label="argsort target",
        )
        return True

    def cross_attention_alignment() -> bool:
        """Cross-attention *is* the alignment: diagonal, anti-diagonal, argsort."""
        data = _load(run, "sort_gap.json")
        if data is None or "alignment" not in data:
            return False
        tasks = [t for t in ("copy", "reverse", "sort") if t in data["alignment"]]
        panels, overlays = [], []
        for task in tasks:
            a = data["alignment"][task]
            panels.append((f"{task} — argmax hits {a['alignment_accuracy']:.0%}", np.array(a["matrix"])))
            overlays.append([(row, col) for row, col in enumerate(a["true_alignment"])])
        first = data["alignment"][tasks[0]]
        heatmap_grid(
            panels,
            title="Cross-attention: where each output token reads from the source",
            xlabel="source position (encoder memory)",
            ylabel="output position (decoder query)",
            cbar_label="cross-attention weight",
            out=_out("h", "cross-attention-alignment"),
            xticklabels=first["source_tokens"],
            overlays=overlays,
            overlay_label="true alignment",
            gamma=0.5,
        )
        return True

    def source_dependency() -> bool:
        """Provable, training-free: a causal stack has exact zeros; an encoder does not."""
        data = _load(run, "sort_gap.json")
        if data is None or "source_dependency" not in data:
            return False
        # Log scale: the point is *which* entries are exactly zero (structurally
        # unreachable), not the magnitude of the ones that aren't.  On a linear
        # scale the diagonal swamps everything and both panels look identical.
        floor = 1e-6
        panels = {label: np.log10(np.array(m) + floor) for label, m in data["source_dependency"].items()}
        attention_heatmap(
            panels,
            title="Which source positions each source representation can see (untrained)",
            xlabel="source position changed",
            ylabel="source representation",
            out=_out("h", "source-dependency"),
            cmap="cividis",
            vmin=np.log10(floor),
            cbar_label="log₁₀ ‖Δ representation‖  (floor = no dependence)",
        )
        return True

    return [
        ("alignment", alignment),
        ("cross-attention-alignment", cross_attention_alignment),
        ("source-dependency", source_dependency),
    ]


def _figs_i(pinned: str | None) -> _Builders:
    run = _resolve(pinned, "linear")

    def cost() -> bool:
        data = _load(run, "linear_benchmark.json")
        if data is None or "cost" not in data:
            return False
        c = data["cost"]
        baseline = c["softmax_seconds"][0]
        series = {
            "softmax": (c["length"], relative_to_baseline(c["softmax_seconds"], baseline)),
            "linear": (c["length"], relative_to_baseline(c["linear_seconds"], baseline)),
        }
        line_plot(
            series,
            title="Forward cost vs sequence length",
            xlabel="sequence length",
            ylabel="time (× softmax @ shortest; machine-relative)",
            out=_out("i", "cost-vs-length"),
            logx=True,
            logy=True,
        )
        return True

    def recall() -> bool:
        data = _load(run, "linear_benchmark.json")
        if data is None or "recall" not in data:
            return False
        r = data["recall"]
        series = {label: (r["num_pairs"], r[label]) for label in ("softmax", "linear") if label in r}
        line_plot(
            series,
            title="Associative recall vs stored pairs",
            xlabel="stored pairs",
            ylabel="token accuracy",
            out=_out("i", "recall-vs-load"),
        )
        return True

    def snr() -> bool:
        data = _load(run, "linear_benchmark.json")
        if data is None or "snr" not in data:
            return False
        s = data["snr"]
        line_plot(
            {"linear-state retrieval": (s["num_pairs"], s["snr"])},
            title="Retrieval SNR vs stored pairs (training-free)",
            xlabel="stored pairs",
            ylabel="signal-to-noise ratio",
            out=_out("i", "snr"),
            logy=True,
        )
        return True

    return [("cost-vs-length", cost), ("recall-vs-load", recall), ("snr", snr)]


