"""Figure dispatcher: ``plot.py <task> [--fig NAME] [--run NAME]``.

Thin glue — loads the saved data for a task from ``results/runs/`` and calls
the relevant ``attention.plotting`` function(s), writing PNGs to
``results/figures/<task>-<name>.png``.  No plotting math lives here.  If a
task has no data yet, it warns cleanly and exits without error.

``fig-a`` is a no-op placeholder (Task A has no training or data to plot;
the first real figure is Task B's training curve).  Timing/memory axes are
machine-relative (a ratio to a baseline the demo measured on this machine),
never absolute seconds.

Provided — students run this; they do not edit it.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Callable

import numpy as np

from attention.plotting.bars import grouped_bars
from attention.plotting.curves import line_grid, line_plot
from attention.plotting.heatmap import attention_heatmap, diagonal_overlay
from attention.plotting.maps import heatmap_grid
from attention.plotting.scoreboard import scoreboard_heatmap
from attention.plotting.style import relative_to_baseline
from attention.vocab import N_CONTENT

_RESULTS = Path(__file__).resolve().parents[1] / "results"
_FIGURES = _RESULTS / "figures"

# Every battery run whose scoreboard.json feeds the cumulative heatmap
# (rows accumulate as later tasks land their demos).
_BATTERY_TAGS = [
    ("rnn", "RNN"),
    ("rnn-attn", "RNN+bahdanau"),
    ("self-attn", "self-attention"),
    ("multihead", "multi-head"),
    ("transformer", "decoder-only"),
    ("sort-gap", "encoder-decoder"),
]

# One builder per figure: returns True if it plotted, False if its data is
# not on disk yet.
_Builders = list[tuple[str, Callable[[], bool]]]


def _resolve(pinned: str | None, tag: str) -> Path | None:
    """The run directory for *tag* (or the ``--run``-pinned one)."""
    if pinned is not None:
        path = Path(pinned)
        if not path.is_absolute():
            path = _RESULTS / "runs" / pinned
        return path if path.is_dir() else None
    from attention.run import latest_run

    return latest_run(_RESULTS, tag)


def _load(run_dir: Path | None, name: str) -> Any:
    if run_dir is None:
        return None
    path = run_dir / name
    if not path.exists():
        return None
    with open(path) as fh:
        return json.load(fh)


def _out(task: str, name: str) -> str:
    return str(_FIGURES / f"{task}-{name}.png")


def _accuracies(scoreboard: dict[str, Any]) -> dict[str, float]:
    return {task: row["accuracy"] for task, row in scoreboard["rows"].items()}


def _cumulative_scoreboard() -> Callable[[], bool]:
    """Heatmap over every battery scoreboard produced so far.

    Task-independent — always written to ``battery.png`` (the figure spans
    every mechanism, not one task), regenerated by ``fig-battery`` whenever a
    battery-contributing task's demo runs.
    """

    def build() -> bool:
        boards: dict[str, dict[str, float]] = {}
        for tag, label in _BATTERY_TAGS:
            sb = _load(_resolve(None, tag), "scoreboard.json")
            if sb is not None:
                boards[label] = _accuracies(sb)
        if not boards:
            return False
        scoreboard_heatmap(boards, title="Battery scoreboard (token accuracy)", out=str(_FIGURES / "battery.png"))
        return True

    return build


